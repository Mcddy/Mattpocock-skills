def compute(check, env=None):
    """Value of one check as text. Raises CheckError when the check itself is malformed."""
    op, args = check.get("op"), check.get("args", [])
    if op not in OPS:
        raise CheckError('unknown check operation "%s"' % op)
    real = []
    for a in args:
        if isinstance(a, str) and a.startswith("$"):
            if env is None or a[1:] not in env:
                raise CheckError('the check uses %s, which is not a variable here' % a)
            v = env[a[1:]]
            real.append(int(v) if float(v).is_integer() else v)
        else:
            real.append(a)
    try:
        return str(OPS[op](*real))
    except CheckError:
        raise
    except Exception as e:  # noqa: BLE001  (a malformed argument must not stop the run)
        raise CheckError("check %s(%s) could not be computed: %s" % (op, ", ".join(str(a) for a in args), str(e)[:80]))


def has_token(text, token):
    """True when token stands in text as a whole value, not as part of a longer number or address."""
    t, k = text.lower(), str(token).lower()
    i = t.find(k)
    while i >= 0:
        before = t[i - 1] if i > 0 else " "
        after = t[i + len(k):i + len(k) + 2]
        ok_before = not (before.isalnum() or before in "./^")
        ok_after = not (after[:1].isalnum() or (after[:1] == "." and after[1:2].isdigit()))
        if ok_before and ok_after:
            return True
        i = t.find(k, i + 1)
    return False


def norm(s):
    return re.sub(r"\s+", "", str(s)).lower()


def checks_of(holder):
    out = []
    if isinstance(holder.get("check"), dict):
        out.append(holder["check"])
    if isinstance(holder.get("checks"), list):
        out += [c for c in holder["checks"] if isinstance(c, dict)]
    return out


def has_digit(s):
    return isinstance(s, str) and re.search(r"\d", s) is not None


def block_text(b):
    parts = [b.get("label", ""), b.get("text", "")] + list(b.get("items", [])) + list(b.get("head", []))
    for r in b.get("rows", []):
        parts += list(r)
    return "  ".join(str(p) for p in parts)


class Tally:
    def __init__(self):
        self.errors, self.advisories, self.listing = [], [], []
        self.prose = {}   # kind -> [number of statements holding digits, [(where, text) not recomputed]]
        self.counts = {"items": 0, "typed answers": 0, "worked steps": 0, "cards": 0, "visual facts": 0, "visual formulas": 0, "settings swept": 0,
                       "grid rows": 0, "text blocks": 0, "pattern claims": 0, "conceptual answers (no number to recompute)": 0}

    def err(self, where, msg):
        self.errors.append("%s: %s" % (where, msg))

    def prose_seen(self, kind, where, text, recomputed):
        """Record one statement that holds digits: recomputed by a check or pattern, or left for a person."""
        rec = self.prose.setdefault(kind, [0, []])
        rec[0] += 1
        if not recomputed:
            rec[1].append((where, text))

    def unread(self):
        return sum(len(v[1]) for v in self.prose.values())

    def ok(self, kind, where, what):
        self.counts[kind] += 1
        self.listing.append("%s: %s" % (where, what))


def tokens_ok(T, where, text, checks, pieces=False, env=None):
    """Log an error for every computed value the text does not state. True when all are stated."""
    good = True
    for c in checks:
        try:
            want = compute(c, env)
        except CheckError as e:
            T.err(where, str(e))
            good = False
            continue
        for piece in (want.split(", ") if pieces else [want]):
            if not has_token(text, piece):
                T.err(where, 'computed %s(%s) = "%s", which the text does not state: "%s"' % (c.get("op"), ", ".join(str(a) for a in c.get("args", [])), piece, text.strip()[:90]))
                good = False
    return good


def expect_tokens(T, kind, where, text, checks, pieces=False, env=None):
    good = tokens_ok(T, where, text, checks, pieces, env)
    if good and checks:
        T.ok(kind, where, "; ".join("%s = %s" % (c.get("op"), compute(c, env)) for c in checks))
    return good


def check_item(T, where, item):
    opts = [o for o in item.get("options", []) if isinstance(o, dict)]
    right = [o for o in opts if o.get("correct") is True]
    checks = checks_of(item)
    if len(right) != 1:
        T.err(where, "does not have exactly one correct option")
        return
    if not checks:
        if has_digit(right[0].get("text")):
            T.err(where, 'the correct option "%s" contains a number and the item has no check' % right[0]["text"][:50])
        else:
            T.counts["conceptual answers (no number to recompute)"] += 1
        return
    try:
        wants = [compute(c) for c in checks]
    except CheckError as e:
        T.err(where, str(e))
        return
    missing = [w for w in wants if not has_token(right[0]["text"], w)]
    if missing:
        T.err(where, 'the option marked correct is "%s" but the computed answer is "%s"' % (right[0]["text"][:60], "; ".join(wants)))
        return
    for o in opts:
        if o is not right[0] and all(has_token(o.get("text", ""), w) for w in wants):
            T.err(where, 'the option "%s" is marked wrong but states the computed answer "%s"' % (o.get("text", "")[:60], "; ".join(wants)))
            return
    T.ok("items", where, "correct option states " + "; ".join(wants))


def check_answer(T, where, a):
    checks = checks_of(a)
    if not checks:
        if has_digit(a.get("answer")):
            T.err(where, 'the answer "%s" contains a number and has no check' % a.get("answer"))
        else:
            T.counts["conceptual answers (no number to recompute)"] += 1
        return
    if len(checks) == 1:
        try:
            want = compute(checks[0])
        except CheckError as e:
            T.err(where, str(e))
            return
        if norm(a.get("answer")) != norm(want):
            T.err(where, 'the stated answer is "%s" but the computed answer is "%s"' % (a.get("answer"), want))
        else:
            T.ok("typed answers", where, "answer %s" % want)
    else:
        expect_tokens(T, "typed answers", where, str(a.get("answer")), checks)


def check_step(T, where, s):
    if "blank" in s:
        return check_answer(T, where + " blank", s["blank"])
    checks = checks_of(s)
    in_result = [c for c in checks if c.get("in") != "text"]
    in_text = [c for c in checks if c.get("in") == "text"]
    if has_digit(s.get("result")) and not in_result:
        T.err(where, 'the result "%s" contains a number and has no check' % s.get("result"))
        return
    if not checks:
        return
    good = tokens_ok(T, where + " (its text)", s.get("text", ""), in_text)
    good = tokens_ok(T, where, str(s.get("result", "")), in_result) and good
    if good:
        T.ok("worked steps", where, "; ".join("%s = %s" % (c.get("op"), compute(c)) for c in checks))


def sweep(params):
    names = [p[0] for p in params]
    for combo in itertools.product(*[p[1] for p in params]):
        yield dict(zip(names, combo))


def frange(lo, hi, step):
    out, v = [], lo
    while v <= hi + 1e-9:
        out.append(v)
        v += step
    return out


def output_text(o, env):
    if isinstance(o.get("parts"), list):
        join = o.get("join", " ")
        return join.join(vc.format_value(vc.formula_eval(f, env), o.get("format", "int")) for f in o["parts"])
    return vc.format_value(vc.formula_eval(o.get("formula"), env), o.get("format", "int"))


def check_outputs(T, where, outputs, params):
    for i, o in enumerate(outputs or []):
        w = '%s output "%s"' % (where, o.get("label", i + 1))
        checks = checks_of(o)
        if not checks:
            T.err(w, "a computed output has no check")
            continue
        bad, n = None, 0
        for env in sweep(params):
            n += 1
            try:
                want = compute(checks[0], env)
            except CheckError as e:
                bad = str(e)
                break
            got = output_text(o, env)
            if got != want:
                bad = "at %s the formula gives %s and the computed value is %s" % (", ".join("%s = %g" % kv for kv in sorted(env.items())), got, want)
                break
        if bad:
            T.err(w, bad)
        else:
            T.counts["settings swept"] += n
            T.ok("visual formulas", w, "formula agrees at all %d settings" % n)


def check_visual(T, where, v):
    t = v.get("type")
    if t == "slider":
        params = [(p["name"], frange(p["min"], p["max"], p.get("step", 1))) for p in v.get("params", [])]
        check_outputs(T, where, v.get("outputs"), params)
    elif t == "number-line":
        p = v["point"]
        params = [(p["name"], frange(v["min"], p.get("max", v["max"]), p.get("step", 1)))]
        if isinstance(v.get("choice"), dict):
            params.append((v["choice"]["name"], [o["value"] for o in v["choice"]["options"]]))
        check_outputs(T, where, v.get("readouts"), params)
    elif t == "table-builder":
        for c in v.get("columns", []):
            if c.get("given") is True:
                continue
            w = '%s column "%s"' % (where, c.get("label"))
            checks = checks_of(c)
            if not checks:
                T.err(w, "a computed column has no check")
                continue
            bad = None
            for i, row in enumerate(v.get("rows", [])):
                try:
                    want = compute(checks[0], row)
                except CheckError as e:
                    bad = str(e)
                    break
                got = vc.format_value(vc.formula_eval(c.get("formula"), row), c.get("format", "int"))
                if got != want:
                    bad = "in row %d the formula gives %s and the computed value is %s" % (i + 1, got, want)
                    break
            if bad:
                T.err(w, bad)
            else:
                T.ok("visual formulas", w, "formula agrees in all %d rows" % len(v.get("rows", [])))
    elif t == "compare":
        for si, s in enumerate(v.get("states", [])):
            for f in s.get("facts", []):
                w = '%s state %d fact "%s"' % (where, si + 1, f.get("label"))
                checks = checks_of(f)
                if not checks:
                    if has_digit(f.get("value")):
                        T.err(w, 'the value "%s" contains a number and has no check' % f.get("value"))
                    continue
                try:
                    want = compute(checks[0])
                except CheckError as e:
                    T.err(w, str(e))
                    continue
                if norm(f.get("value")) != norm(want):
                    T.err(w, 'the stated value is "%s" but the computed value is "%s"' % (f.get("value"), want))
                else:
                    T.ok("visual facts", w, want)
            for gi, g in enumerate(s.get("segments", [])):
                w = "%s state %d segment %d" % (where, si + 1, gi + 1)
                checks = checks_of(g)
                if not checks:
                    T.err(w, "a segment size has no check")
                    continue
                try:
                    want = compute(checks[0])
                except CheckError as e:
                    T.err(w, str(e))
                    continue
                if str(g.get("size")) != want:
                    T.err(w, "the size is %s but the computed value is %s" % (g.get("size"), want))
                else:
                    T.ok("visual facts", w, want)
    elif t == "steps":
        rows = v.get("rows") or []
        for c in v.get("checks", []) if isinstance(v.get("checks"), list) else []:
            if "row" not in c:
                continue
            w = "%s row %d" % (where, c["row"] + 1)
            try:
                want = compute(c)
            except CheckError as e:
                T.err(w, str(e))
                continue
            cells = rows[c["row"]].get("cells", []) if c["row"] < len(rows) else []
            got = ", ".join(cells) if ", " in want else "".join(cells)
            if got != want:
                T.err(w, 'the row reads "%s" but the computed value is "%s"' % (got, want))
            else:
                T.ok("grid rows", w, want)
        unchecked = [i + 1 for i, r in enumerate(rows) if any(has_digit(x) for x in r.get("cells", []))
                     and not any(isinstance(c, dict) and c.get("row") == i for c in (v.get("checks") or []))]
        if unchecked:
            T.err(where, "grid row(s) %s hold numbers and have no check" % ", ".join(str(u) for u in unchecked))
        for i, s in enumerate(v.get("steps", [])):
            cks = checks_of(s)
            if cks:
                expect_tokens(T, "text blocks", "%s step %d caption" % (where, i + 1), s.get("caption", ""), cks, pieces=True)
    loose = [c for c in (v.get("checks") or []) if isinstance(c, dict) and "row" not in c]
    if loose:
        text = "  ".join([v.get("caption", "")] + [s.get("name", "") for s in v.get("states", [])] +
                         [g.get("label", "") for s in v.get("states", []) for g in s.get("segments", [])])
        expect_tokens(T, "text blocks", where + " caption and labels", text, loose, pieces=True)


def check_blocks(T, where, blocks):
    for i, b in enumerate(blocks or []):
        w = "%s block %d (%s)" % (where, i + 1, b.get("label") or b.get("type"))
        cks = checks_of(b)
        text = block_text(b)
        if cks:
            expect_tokens(T, "text blocks", w, text, cks, pieces=True)
        elif has_digit(text) and not b.get("source"):
            T.advisories.append('%s contains digits and was not recomputed: "%s"' % (w, text.strip()[:70]))


