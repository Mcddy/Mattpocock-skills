BITS = ipa.IPV4LENGTH
OCTETS = len(ipa.IPv4Address("0.0.0.0").packed)
OCTET_BITS = BITS // OCTETS
OCTET_MAX = max(ipa.IPv4Address("255.255.255.255").packed)


class CheckError(Exception):
    pass


def _net(prefix):
    return ipa.ip_network("0.0.0.0/%d" % prefix)


def _iface(ip, prefix):
    return ipa.ip_interface("%s/%d" % (ip, prefix)).network


def _nth(parent, new_prefix, n):
    subs = list(ipa.ip_network(parent).subnets(new_prefix=new_prefix))
    if not 1 <= n <= len(subs):
        raise CheckError("there is no subnet number %d: /%d makes %d of %s" % (n, new_prefix, len(subs), parent))
    return subs[n - 1]


def _usable(prefix):
    if prefix > 30:
        raise CheckError("usable hosts are defined here only up to /30")
    n = _net(prefix).num_addresses - 2
    if prefix >= 20 and n != sum(1 for _ in _net(prefix).hosts()):
        raise CheckError("host count disagrees with ipaddress.hosts()")
    return n


def _subnets(a, b):
    return len(list(ipa.ip_network("10.0.0.0/%d" % a).subnets(new_prefix=b)))


def _bits_for(n):
    s = 0
    while 2 ** s < n:
        s += 1
    return s


def _block(prefix):
    for o in _net(prefix).netmask.packed:
        if o != OCTET_MAX:
            return 256 - o
    return 1


def _prefix_for_hosts(n):
    best = None
    for p in range(1, 31):
        if _usable(p) >= n:
            best = p
    if best is None:
        raise CheckError("no prefix length holds %d hosts" % n)
    return best


def _invalid(*candidates):
    bad = []
    for c in candidates:
        try:
            ipa.IPv4Address(c)
        except ValueError:
            bad.append(c)
    if len(bad) != 1:
        raise CheckError("expected exactly one invalid address among %s, found %d" % (", ".join(candidates), len(bad)))
    return bad[0]


def _invalid_mask(m):
    try:
        ipa.IPv4Network("0.0.0.0/" + m)
    except ValueError:
        return m
    raise CheckError("%s is a valid mask, but the text says it is not" % m)


def _nl_prefix(b):
    b = int(b)
    if b < 1 or b & (b - 1):
        raise CheckError("block size %s is not a power of two" % b)
    return BITS - (b.bit_length() - 1)


def _nl(x, b):
    return _iface("192.0.2.%d" % int(x), _nl_prefix(b))


def _mask_octets_all():
    return sorted({o for p in range(0, BITS + 1) for o in _net(p).netmask.packed})


def _greedy_step(n, pos):
    """Position pos (1 is the leftmost) of the subtract-the-place-values method: place value, what remains before, the bit written, what remains after."""
    left = n
    for k in range(OCTET_BITS - 1, -1, -1):
        place = 2 ** k
        bit = 1 if place <= left else 0
        if OCTET_BITS - k == pos:
            return "%d, %d, %d, %d" % (place, left, bit, left - place * bit)
        left -= place * bit
    raise CheckError("an octet has no position %s" % pos)


def _remainders(n):
    out, left = [], n
    for k in range(OCTET_BITS - 1, -1, -1):
        out.append(str(left))
        if 2 ** k <= left:
            left -= 2 ** k
    return ", ".join(out)


