            ew = "%s worked %s" % (mw, ex.get("id"))
            for lv in ("full", "partial"):
                for i, s in enumerate(ex.get(lv, {}).get("steps", [])):
                    check_step(T, "%s %s step %d" % (ew, lv, i + 1), s)
                    in_text = [c for c in checks_of(s) if c.get("in") == "text"]
                    note_prose(T, "worked step text and hints", "%s %s step %d text" % (ew, lv, i + 1), s.get("text", ""), in_text)
                    if isinstance(s.get("blank"), dict):
                        note_prose(T, "worked step text and hints", "%s %s step %d hint" % (ew, lv, i + 1), s["blank"].get("hint", ""))
