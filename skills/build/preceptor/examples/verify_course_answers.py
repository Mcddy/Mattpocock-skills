def _walk(node, path):
    if isinstance(node, dict):
        yield path, node
        for k, v in node.items():
            for x in _walk(v, path + (k,)):
                yield x
    elif isinstance(node, list):
        for i, v in enumerate(node):
            for x in _walk(v, path + (i,)):
                yield x


def selftest(course):
    import copy
    results = []
    base = verify(copy.deepcopy(course))
    results.append(("the course as given verifies with no errors", not base.errors, "; ".join(base.errors[:2])))
    for name, change in _plants(course):
        c = copy.deepcopy(course)
        change(c)
        T = verify(c)
        results.append(("planted fault caught: " + name, bool(T.errors), T.errors[0] if T.errors else "the verifier did not notice"))
    return results



def emit(text):
    try:
        sys.stdout.write(text.encode("ascii", "replace").decode("ascii") + "\n")
        sys.stdout.flush()
    except BrokenPipeError:
        pass


def main(argv):
    flags, args = set(), []
    for a in argv:
        if a in FLAGS:
            flags.add(a)
        elif a.startswith("--"):
            print("verify_course_answers: unknown option " + a, file=sys.stderr)
            return 2
        else:
            args.append(a)
    if len(args) != 1:
        if not argv:
            print(__doc__)
        else:
            print("verify_course_answers: expected one course file (page or JSON)", file=sys.stderr)
        return 2
    try:
        course, _ = vc.read_course(args[0])
    except vc.InputError as e:
        print("verify_course_answers: %s" % e, file=sys.stderr)
        return 2
    if "--selftest" in flags:
        results = selftest(course)
        failed = [r for r in results if not r[1]]
        if "--json" in flags:
            emit(json.dumps({"checks": [{"check": r[0], "ok": r[1], "detail": r[2]} for r in results], "failed": len(failed), "total": len(results)}, indent=1, ensure_ascii=True))
        else:
            for name, ok, detail in results:
                shown = detail if (detail and (not ok or name.startswith("planted"))) else ""
                emit("%-5s %s%s" % ("PASS" if ok else "FAIL", name, ("\n      " + shown[:200]) if shown else ""))
            emit("RESULT: %s. %d of %d checks passed. The course file itself was not changed." % ("FAIL" if failed else "PASS", len(results) - len(failed), len(results)))
        return 1 if failed else 0
    T = verify(course)
    recomputed = sum(v for k, v in T.counts.items() if k not in ("settings swept", "conceptual answers (no number to recompute)"))
    if "--json" in flags:
        emit(json.dumps({"course": course.get("id"), "version": course.get("version"), "errors": T.errors, "advisories": T.advisories,
                         "counts": T.counts, "recomputed": recomputed,
                         "statements_with_digits": {k: {"total": v[0], "not_recomputed": len(v[1]),
                                                        "list": [{"where": w, "text": t} for w, t in v[1]] if "--list" in flags else None}
                                                    for k, v in T.prose.items()},
                         "checked": T.listing if "--list" in flags else None}, indent=1, ensure_ascii=True))
        return 1 if T.errors else 0
    lines = ["verify_course_answers: %s version %r" % (course.get("id"), course.get("version"))]
    if "--list" in flags:
        lines += ["  OK        " + x for x in T.listing]
    lines += ["  ERROR     " + e for e in T.errors]
    lines += ["  ADVISORY  " + a for a in T.advisories]
    for kind, (total, left) in T.prose.items():
        if "--list" in flags:
            lines += ["  READ      %s: %s" % (w, t) for w, t in left]
        if left:
            lines.append("  ADVISORY  %s: %d of the %d that contain digits were recomputed by no check or pattern. Read them (--list prints each)" % (kind, len(left), total))
    for k, v in T.counts.items():
        lines.append("  %-45s %d" % (k, v))
    lines.append("RESULT: %s. %d value(s) recomputed, %d error(s). Left for a person to read: %d block(s) and %d other statement(s) that contain digits. Recomputing a number says nothing about how well it is explained."
                 % ("FAIL" if T.errors else "PASS", recomputed, len(T.errors), len(T.advisories), T.unread()))
    emit("\n".join(lines))
    return 1 if T.errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
