#!/usr/bin/env python3
"""Recompute every numeric answer in the IPv4 subnetting course with Python's ipaddress module.

Usage:
  python verify_course_answers.py COURSE [--json] [--list]
  python verify_course_answers.py COURSE --selftest [--json]

COURSE is the course page (.html) or its JSON. Standard library only. Reads the file, changes nothing.

How it works. The course carries a "check" field beside each answer: an operation name and its
arguments, for example {"op": "network", "args": ["192.168.10.77", 26]}. This script computes the
operation from scratch (ipaddress for everything about addresses, whole-number arithmetic for
binary) and compares the result with what the course says. The answers in the course were typed
by hand; nothing in the course was generated by this script.

What it enforces (ERROR, exit 1):
  - practice and gate items: the option marked correct contains the computed value, and no other
    option does
  - blanks, independent answers and challenge tasks: the stated answer equals the computed value
  - worked steps, cards, facts in compare visuals: the text contains the computed value
  - slider and number-line outputs: the engine's formula, evaluated at every setting the control
    can take, equals the computed value at that setting
  - table-builder columns: the formula's value equals the computed value in every row
  - step-by-step grids: each checked row equals the computed bits
  - any of the above that contains a digit and has no check is an error: every numeric answer
    must be recomputed
  - statements found by pattern anywhere in the text are recomputed too: sums and powers
    ("128 + 64 = 192", "`2^8` is 256"), binary values ("224 is `11100000`"), and the stock phrases
    of the explanations ("A /28 holds 14", "the largest multiple of 16 that is not above 77 is 64",
    "the block runs from 96 to 127", "Under /26 the blocks are 64 wide", "Nine subnets force 4
    borrowed bits")
  - explanations that say what a wrong option is ("That is the last usable host", "That is the
    fourth subnet", "That is the network address under /24") are recomputed for the address the
    item is about and compared with the option's own text
What it reports for a person to read (ADVISORY):
  - theory, cheat-sheet and challenge-brief blocks that contain digits and carry no check and no source
  - for option explanations, worked step text and hints, visual captions and prompts, and
    definitions, objectives and summaries: how many contain digits, and how many of those no check
    or pattern recomputed. --list prints each one (READ lines). These are prose a person must read:
    a pattern recognises a phrase, it does not understand a sentence.
  Stems, problem statements and card fronts are not listed: they pose a case, they do not claim.
--selftest proves the checks can fail. It makes copies of the course in memory, plants one wrong
value in each (a wrong option marked correct, a wrong blank, a wrong card, a wrong formula, a
false sum, a false explanation of a wrong option, a wrong remainder in a caption, a check removed,
and so on) and confirms that each copy is reported.

What it cannot tell: whether an explanation is well put, whether a conceptual answer with no
number in it is right, or whether "accept" spellings of an answer are sensible. Custom visuals
run code in the page and are exercised by the browser test, not here.

Exit codes: 0 nothing failed. 1 a check failed. 2 bad arguments or unreadable input.
"""
