BUCKET_OF = {n: b for b, names in BUCKETS.items() for n in names.split()}

# Findings that are known to be false positives: (skill, substring of message).
LINT_EXCEPTIONS = [("skill-creator", "evals/evals.json")]


def all_skills():
    """Sorted list of (bucket, name, path)."""
    out = []
    for md in sorted(SKILLS.glob("*/*/SKILL.md")):
        out.append((md.parent.parent.name, md.parent.name, md.parent))
    return out


def frontmatter(path):
    fm, _ = skill_lint.split_frontmatter((path / "SKILL.md").read_text(encoding="utf-8"))
    return skill_lint.parse_frontmatter(fm or [])


def short_description(fm):
    d = re.sub(r"^[>|][-+]?\s*", "", fm.get("description", "")).strip()
    d = re.sub(r"\s+", " ", d)
    first = re.split(r"(?<=[.!?])\s", d, maxsplit=1)[0]
    first = first if len(first) <= 160 else first[:157].rstrip() + "..."
    return first.replace("|", "\\|")


# ---------------------------------------------------------------- registry
def build_registry():
    lines = [
        "# Registry",
        "",
        "Generated by `python scripts/skills.py registry`. Do not edit by hand.",
        "",
        "**User** = only runs when you type its name. **Auto** = the agent may also pick it up from its description.",
        "",
    ]
    by_bucket = {}
    for bucket, name, path in all_skills():
        by_bucket.setdefault(bucket, []).append((name, path))
    total = sum(len(v) for v in by_bucket.values())
    lines.append(f"{total} skills in {len(by_bucket)} buckets.")
    lines.append("")
    for bucket in sorted(by_bucket):
        lines += [f"## {bucket} ({len(by_bucket[bucket])})", "", "| Skill | Invocation | What it does |", "| --- | --- | --- |"]
        for name, path in by_bucket[bucket]:
            fm = frontmatter(path)
            inv = "User" if fm.get("disable-model-invocation", "").lower() == "true" else "Auto"
            rel = path.relative_to(ROOT).as_posix()
            lines.append(f"| [{name}]({rel}/SKILL.md) | {inv} | {short_description(fm)} |")
        lines.append("")
    lines += [
        "## Not vendored",
        "",
        "Installed in Claude but deliberately not copied here. The host ships and updates them, and the first seven are proprietary.",
        "",
        ", ".join(f"`{n}`" for n in sorted(EXCLUDE)),
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------- manifests
def build_manifests():
    skills = [f"./{p.relative_to(ROOT).as_posix()}" for b, n, p in all_skills() if b not in HOLDING]
    plugin = {
        "name": PLUGIN_NAME,
        "description": "Shaun's agent skills: engineering flows, research, analysis, build and creative tooling.",
        "author": {"name": "Shaun"},
        "license": "MIT",
        "icon": "./.claude-plugin/icon.png",
        "skills": skills,
    }
    market = {
        "name": "shaun",
        "owner": {"name": "Shaun"},
        "description": "Shaun's skill library.",
        "plugins": [{"name": PLUGIN_NAME, "source": "./", "description": plugin["description"]}],
    }
    return {".claude-plugin/plugin.json": plugin, ".claude-plugin/marketplace.json": market}


def write_if_changed(path, text, check):
    cur = path.read_text(encoding="utf-8") if path.exists() else None
    if cur == text:
        return True
    if check:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def cmd_registry(a, check=False):
    return write_if_changed(ROOT / "REGISTRY.md", build_registry(), check)


def cmd_manifests(a, check=False):
    ok = True
    for rel, obj in build_manifests().items():
        ok &= write_if_changed(ROOT / rel, json.dumps(obj, indent=2) + "\n", check)
    return ok


# ---------------------------------------------------------------- check
def cmd_check(a):
    bad = 0
    names = {}
    for bucket, name, path in all_skills():
        if name in names:
            print(f"ERROR duplicate skill name {name}: {names[name]} and {bucket}")
            bad += 1
        names[name] = bucket
        res = skill_lint.lint_skill(path)
        for e in res["errors"]:
            if any(s == name and sub in e for s, sub in LINT_EXCEPTIONS):
                continue
            print(f"ERROR {bucket}/{name}: {e}")
            bad += 1
    for label, ok in (("REGISTRY.md", cmd_registry(a, True)), ("manifests", cmd_manifests(a, True))):
        if not ok:
            print(f"ERROR {label} is stale: run `python scripts/skills.py sync`")
            bad += 1
    print(f"{len(names)} skills checked, {bad} problem(s)")
    return bad == 0


# ---------------------------------------------------------------- install
def link_or_copy(src, dest, copy):
    if dest.is_symlink() or dest.is_file():
        dest.unlink()
    elif dest.exists():
        shutil.rmtree(dest)
    if not copy:
        try:
            dest.symlink_to(src, target_is_directory=True)
            return "linked"
        except OSError:
            pass  # Windows without developer mode: fall back to a copy
    shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__"))
    return "copied"


def cmd_install(a):
    targets = {"claude": Path.home() / ".claude" / "skills", "codex": Path.home() / ".agents" / "skills"}
    only = set(a.only.split(",")) if a.only else None
    for t in a.targets.split(","):
        dest_root = targets[t]
        if dest_root.is_symlink() and ROOT in dest_root.resolve().parents:
            sys.exit(f"{dest_root} is a symlink into this repo; remove it and re-run")
        dest_root.mkdir(parents=True, exist_ok=True)
        n = 0
        for bucket, name, path in all_skills():
            if (bucket in HOLDING and not a.all) or (only and bucket not in only):
                continue
            how = link_or_copy(path, dest_root / name, a.copy)
            n += 1
        print(f"{t}: {n} skills ({how}) -> {dest_root}")
    print("Copies do not follow git pulls: re-run install after each pull.") if a.copy else None


# ---------------------------------------------------------------- import
# skills.lock.json records, per imported skill, the hash of the host copy and of the repo copy at the
# last import. That separates "the host changed it" from "the repo changed it":
#   host unchanged                 -> skip (repo edits win)
#   host changed, repo unchanged   -> update
#   host changed, repo changed     -> conflict, skipped unless --force
#   host equals repo               -> in sync, lock refreshed
def tree_hash(path):
    h = hashlib.sha256()
    for f in sorted(p for p in Path(path).rglob("*") if p.is_file() and "__pycache__" not in p.parts and p.name != ".DS_Store"):
        h.update(f.relative_to(path).as_posix().encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def load_lock():
    return json.loads(LOCK.read_text()) if LOCK.exists() else {}


def save_lock(lock):
    LOCK.write_text(json.dumps(dict(sorted(lock.items())), indent=1) + "\n", encoding="utf-8", newline="\n")


def own_plugin_skills(plugins):
    """Skills in plugins you uploaded yourself. Catalog plugins are managed upstream and skipped."""
    found = {}
    for meta in sorted(plugins.glob("*.meta.json")):
        if json.loads(meta.read_text()).get("marketplace_kind") != "account_uploads":
            continue
        for d in sorted((plugins / meta.name[: -len(".meta.json")] / "skills").glob("*")):
            if (d / "SKILL.md").exists():
                found.setdefault(d.name, d)
    return found


def copy_skill(src, dest):
    if dest.exists():
        shutil.rmtree(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(src, dest, ignore=shutil.ignore_patterns("__pycache__", ".DS_Store"))


def cmd_import(a):
    cands = {d.name: d for d in sorted(a.source.iterdir()) if (d / "SKILL.md").exists()}
    if a.plugins:
        for n, d in own_plugin_skills(a.plugins).items():
            cands.setdefault(n, d)
    existing = {n: p for b, n, p in all_skills()}
    lock = load_lock()
    count = dict(added=0, updated=0, unchanged=0, kept=0, conflict=0)
    for name, src in cands.items():
        if name in EXCLUDE:
            continue
        cur, src_h = existing.get(name), tree_hash(src)
        entry = lock.get(name)
        if cur is None:
            dest = SKILLS / BUCKET_OF.get(name, "inbox") / name
            print(f"add      {name} -> {dest.relative_to(ROOT).as_posix()}")
            if not a.dry_run:
                copy_skill(src, dest)
                lock[name] = {"source": src_h, "repo": src_h}
            count["added"] += 1
            continue
        repo_h = tree_hash(cur)
        if src_h == repo_h:
            lock[name] = {"source": src_h, "repo": repo_h}
            count["unchanged"] += 1
        elif entry and src_h == entry["source"]:
            count["kept"] += 1  # host untouched since last import; repo edits win
        elif entry and repo_h == entry["repo"] or a.force:
            print(f"update   {name}" + (" (forced)" if a.force and not (entry and repo_h == entry["repo"]) else ""))
            if not a.dry_run:
                copy_skill(src, cur)
                lock[name] = {"source": src_h, "repo": src_h}
            count["updated"] += 1
        else:
            why = "changed in both the host and the repo" if entry else "differs and was never imported"
            print(f"CONFLICT {name}: {why}; skipped (diff it, then re-run with --force to take the host copy)")
            count["conflict"] += 1
    if not a.dry_run:
        save_lock(lock)
    print(", ".join(f"{v} {k}" for k, v in count.items()) + (" (dry run)" if a.dry_run else ""))
    if not a.dry_run and (count["added"] or count["updated"]):
        print("Now run: python scripts/skills.py sync")


# ---------------------------------------------------------------- package
def cmd_package(a):
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for bucket, name, path in all_skills():
        if a.only and name not in a.only.split(","):
            continue
        zp = out / f"{name}.zip"
        with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(path.rglob("*")):
                if f.is_file() and "__pycache__" not in f.parts:
                    z.write(f, f"{name}/{f.relative_to(path).as_posix()}")
        n += 1
    print(f"{n} zips in {out}")


def cmd_sync(a):
    cmd_registry(a)
    cmd_manifests(a)
    return cmd_check(a)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    sub.add_parser("registry").set_defaults(fn=cmd_registry)
    sub.add_parser("manifests").set_defaults(fn=cmd_manifests)
    sub.add_parser("sync").set_defaults(fn=cmd_sync)
    p = sub.add_parser("install")
    p.add_argument("--copy", action="store_true", help="copy instead of symlink")
    p.add_argument("--targets", default="claude,codex", help="comma list of: claude, codex")
    p.add_argument("--only", help="comma list of buckets")
    p.add_argument("--all", action="store_true", help="include incubating and inbox")
    p.set_defaults(fn=cmd_install)
    p = sub.add_parser("import")
    p.add_argument("--source", required=True, type=Path, help="folder whose children are skill folders")
    p.add_argument("--plugins", type=Path, help="Claude synced plugins folder (own uploads only)")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--force", action="store_true", help="take the host copy on conflicts")
    p.set_defaults(fn=cmd_import)
    p = sub.add_parser("package")
    p.add_argument("--out", default="dist")
    p.add_argument("--only", help="comma list of skill names")
    p.set_defaults(fn=cmd_package)
    a = ap.parse_args()
    ok = a.fn(a)
    sys.exit(0 if ok in (None, True) else 1)


if __name__ == "__main__":
    main()
