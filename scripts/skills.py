#!/usr/bin/env python3
"""One CLI to keep this skill library and every agent host in step. Python 3.9+, stdlib only.

  skills.py check                  lint every skill, verify registry and manifests are current
  skills.py registry               regenerate REGISTRY.md
  skills.py manifests              regenerate .claude-plugin/*.json
  skills.py install [--copy]       link (or copy) skills into ~/.claude/skills and ~/.agents/skills
  skills.py import --source DIR    pull skills from an installed Claude/ChatGPT/Codex skills folder
  skills.py package                zip each skill (single top-level folder) into dist/ for upload
  skills.py sync                   registry + manifests + check, in that order

The repo is the canonical source. Edit here, then run `install` on each machine.
"""
import argparse, hashlib, json, os, re, shutil, subprocess, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
LOCK = ROOT / "skills.lock.json"
sys.path.insert(0, str(Path(__file__).resolve().parent))
import skill_lint  # noqa: E402

